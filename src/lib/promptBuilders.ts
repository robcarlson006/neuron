/**
 * Parse the auto-card generation response (extended format with subtypes, examples, etc.)
 */
export function parseAutoCardResponse(responseText: string): AutoGeneratedCards {
  let cleaned = responseText.trim()
  if (cleaned.startsWith('```')) {
    cleaned = cleaned.replace(/^```(?:json)?\n?/, '').replace(/\n?```$/, '')
  }

  const parsed = JSON.parse(cleaned)

  if (!parsed.flashcards || !Array.isArray(parsed.flashcards)) {
    throw new Error('Invalid response: missing flashcards array')
  }
  if (!parsed.active_recall || !Array.isArray(parsed.active_recall)) {
    throw new Error('Invalid response: missing active_recall array')
  }

  const validSubtypes = ['definition', 'mechanism', 'application', 'discrimination'] as const
  type CardSubtype = typeof validSubtypes[number]

  const parseCardSubtype = (val: unknown): CardSubtype | undefined =>
    validSubtypes.includes(val as CardSubtype) ? (val as CardSubtype) : undefined

  const flashcards = parsed.flashcards.map((fc: Record<string, unknown>) => {
    if (typeof fc.front !== 'string' || typeof fc.back !== 'string') {
      throw new Error('Invalid flashcard: missing front or back')
    }
    return {
      front: fc.front,
      back: fc.back,
      card_subtype: parseCardSubtype(fc.card_subtype),
      concrete_example: typeof fc.concrete_example === 'string' ? fc.concrete_example : undefined,
      common_mistake: typeof fc.common_mistake === 'string' ? fc.common_mistake : undefined,
      mnemonic: typeof fc.mnemonic === 'string' ? fc.mnemonic : undefined
    } as AutoGeneratedFlashcard
  })

  const active_recall = parsed.active_recall.map((ar: Record<string, unknown>) => {
    if (typeof ar.question !== 'string' || typeof ar.model_answer !== 'string') {
      throw new Error('Invalid active recall: missing question or model_answer')
    }
    return {
      question: ar.question,
      model_answer: ar.model_answer,
      card_subtype: typeof ar.card_subtype === 'string' ? ar.card_subtype : undefined,
      concrete_example: typeof ar.concrete_example === 'string' ? ar.concrete_example : undefined,
      common_mistake: typeof ar.common_mistake === 'string' ? ar.common_mistake : undefined,
      mnemonic: typeof ar.mnemonic === 'string' ? ar.mnemonic : undefined
    }
  })

  return { flashcards, active_recall }
}

