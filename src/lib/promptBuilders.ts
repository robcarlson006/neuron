/**
 * Parse the card generation response (basic format)
 */
export function parseCardGenerationResponse(responseText: string): GeneratedCards {
  const cleaned = cleanMarkdownFences(responseText)

  let parsed: any
  try {
    parsed = JSON.parse(cleaned)
  } catch {
    parsed = JSON.parse(repairJSONString(cleaned))
  }

  if (!parsed.flashcards || !Array.isArray(parsed.flashcards)) {
    throw new Error('Invalid response: missing flashcards array')
  }
  if (!parsed.active_recall || !Array.isArray(parsed.active_recall)) {
    throw new Error('Invalid response: missing active_recall array')
  }

  // Validate flashcard structure
  const flashcards = parsed.flashcards.map((fc: { front?: string; back?: string }) => {
    if (typeof fc.front !== 'string' || typeof fc.back !== 'string') {
      throw new Error('Invalid flashcard: missing front or back')
    }
    return { front: cleanCardBrackets(fc.front), back: cleanCardBrackets(fc.back) }
  })

  // Validate active recall structure
  const active_recall = parsed.active_recall.map((ar: { question?: string; model_answer?: string }) => {
    if (typeof ar.question !== 'string' || typeof ar.model_answer !== 'string') {
      throw new Error('Invalid active recall: missing question or model_answer')
    }
    return { question: cleanCardBrackets(ar.question), model_answer: cleanCardBrackets(ar.model_answer) }
  })

  return { flashcards, active_recall }
}

/**
 * Parse the evaluation response
 */
export function parseEvaluationResponse(responseText: string): EvaluationResult {
  const cleaned = cleanMarkdownFences(responseText)

  let parsed: any
  try {
    parsed = JSON.parse(cleaned)
  } catch {
    parsed = JSON.parse(repairJSONString(cleaned))
  }

  if (typeof parsed.correct !== 'boolean') {
    throw new Error('Invalid evaluation response: missing correct field')
  }
  if (typeof parsed.score !== 'number') {
    throw new Error('Invalid evaluation response: missing score field')
  }
  if (typeof parsed.feedback !== 'string') {
    throw new Error('Invalid evaluation response: missing feedback field')
  }

  let matched_concepts: string[] | undefined
  let missing_concepts: string[] | undefined

  if (Array.isArray(parsed.key_points_analyzed)) {
    matched_concepts = parsed.key_points_analyzed
      .filter((k: any) => k && (k.status === 'recalled' || k.status === 'partially_recalled'))
      .map((k: any) => (typeof k.point === 'string' ? k.point : String(k?.point || k)))
    missing_concepts = parsed.key_points_analyzed
      .filter((k: any) => k && k.status === 'missed')
      .map((k: any) => (typeof k.point === 'string' ? k.point : String(k?.point || k)))
  } else {
    if (Array.isArray(parsed.matched_concepts)) {
      matched_concepts = parsed.matched_concepts.filter((c: unknown) => typeof c === 'string')
    }
    if (Array.isArray(parsed.missing_concepts)) {
      missing_concepts = parsed.missing_concepts.filter((c: unknown) => typeof c === 'string')
    }
  }

  return {
    correct: parsed.correct,
    score: parsed.score,
    feedback: parsed.feedback,
    matched_concepts,
    missing_concepts
  }
}

