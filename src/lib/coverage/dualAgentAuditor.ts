/**
 * Asymmetric Dual-Agent Auditor
 * Implements the Extractor <-> Adversarial Auditor multi-pass loop.
 * Exploits the cognitive asymmetry of LLMs: verification and gap-finding are 3-5x
 * more accurate than single-pass generation.
 */

export interface ExtractedConcept {
  name: string
  definition: string
  governing_formula?: string
  worked_steps?: string[]
  common_misconception?: string
  edge_cases?: string[]
}

export interface Pass1ExtractionResult {
  principles: string[]
  concepts: ExtractedConcept[]
  examples: string[]
}

export interface Pass2AuditResult {
  omitted_theorems_or_rules: string[]
  missed_edge_cases_or_traps: string[]
  underdeveloped_concepts: string[]
}

export interface ReconciledChunkKnowledge {
  chunkIndex: number
  sectionTitle: string
  allPrinciples: string[]
  concepts: ExtractedConcept[]
  misconceptionTraps: string[]
  workedExamples: string[]
}

/**
 * Prompt for Pass 1: Generative Extraction
 */
export function buildPass1ExtractionPrompt(
  chunkText: string,
  sectionTitle: string,
  subjectDomain: string = 'general'
): string {
  return `You are a world-class cognitive learning scientist and subject-matter expert in ${subjectDomain}.
Your mission is to perform an exhaustive, deep semantic extraction of all principles, formulas, definitions, and worked examples from this specific section of course material.

SECTION TITLE: "${sectionTitle}"

SECTION TEXT:
"""
${chunkText}
"""

EXTRACTION DIRECTIVES:
1. Extract every core concept, rule, definition, or theorem introduced in this section.
2. If there are mathematical formulas, balance sheets, or equations, extract them cleanly in LaTeX notation ($...$ and $$...$$).
3. If this section includes a calculation, proof, or worked derivation, extract the landmark intermediate steps.
4. Extract the primary student pitfalls, counter-intuitive traps, or common false assumptions associated with these ideas.
5. Extract specific real-world examples, historical cases, or physical analogies mentioned in the text.

Output ONLY valid JSON matching this schema (no markdown fences, no conversational preamble):
{
  "principles": ["Governing Principle 1", "Formula 2"],
  "concepts": [
    {
      "name": "Concept Name",
      "definition": "Precise explanatory definition",
      "governing_formula": "Optional LaTeX formula or null",
      "worked_steps": ["Step 1", "Step 2"],
      "common_misconception": "Frequent student mistake or trap",
      "edge_cases": ["Boundary condition or exception"]
    }
  ],
  "examples": ["Concrete scenario or illustrative example from text"]
}`
}

/**
 * Prompt for Pass 2: Adversarial Gap-Hunter Audit
 */
export function buildPass2AuditorPrompt(
  chunkText: string,
  sectionTitle: string,
  pass1ExtractionJson: string,
  subjectDomain: string = 'general'
): string {
  return `You are a ruthless, adversarial academic auditor and psychometric inspector in ${subjectDomain}.
You have been provided with:
1. THE SOURCE MATERIAL SECTION: "${sectionTitle}"
2. THE PRELIMINARY EXTRACTION generated by a first-pass AI assistant.

Your SOLE mission is to find what the first pass MISSED, OVERSIMPLIFIED, or GLOSSED OVER.

SOURCE TEXT:
"""
${chunkText}
"""

PRELIMINARY EXTRACTION:
"""
${pass1ExtractionJson}
"""

AUDIT DIRECTIVES (ZERO-TOLERANCE FOR OMISSIONS):
1. Line-by-line inspection: What specific formulas, intermediate mathematical pivots, or theoretical qualifiers in the source text were omitted?
2. Nuances & Exceptions: Did the author mention a boundary condition, an exception to the rule, or an edge case that was ignored in the preliminary extraction?
3. Buried Traps: Are there subtle, counter-intuitive student traps or misconceptions in this section that the first pass failed to identify?
4. Technical terms: Are there specific domain terms, clinical symptoms, statutes, or Latin/scientific designations present in the source text that were left out?

Output ONLY valid JSON matching this schema:
{
  "omitted_theorems_or_rules": ["Specific rule/formula/theorem from the text missed in Pass 1"],
  "missed_edge_cases_or_traps": ["Specific boundary condition, student trap, or exception missed"],
  "underdeveloped_concepts": ["Concepts that were only superficially defined and need deeper technical precision"]
}`
}

/**
 * Reconcile Pass 1 and Pass 2 into an authoritative, complete knowledge model for this chunk.
 */
export function reconcileChunkKnowledge(
  chunkIndex: number,
  sectionTitle: string,
  pass1: Pass1ExtractionResult,
  pass2: Pass2AuditResult
): ReconciledChunkKnowledge {
  const mergedPrinciples = Array.from(
    new Set([
      ...pass1.principles,
      ...pass2.omitted_theorems_or_rules
    ])
  )

  const misconceptionTraps = Array.from(
    new Set([
      ...pass1.concepts.map(c => c.common_misconception).filter((m): m is string => Boolean(m)),
      ...pass2.missed_edge_cases_or_traps
    ])
  )

  return {
    chunkIndex,
    sectionTitle,
    allPrinciples: mergedPrinciples,
    concepts: pass1.concepts,
    misconceptionTraps,
    workedExamples: pass1.examples
  }
}
