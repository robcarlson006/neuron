/**
 * Helper to extract pure numerical value from formatted financial/scientific strings:
 * e.g. "$1,234.50M" -> 1234.50, "(450)" -> -450, "12.5%" -> 12.5, "0.412***" -> 0.412
 */
export function extractNumericCell(cellStr: string): { num: number; hasValue: boolean; isNegative: boolean } {
  if (!cellStr || typeof cellStr !== 'string') return { num: 0, hasValue: false, isNegative: false }

  const cleaned = cellStr.replace(/[*_$€£¥%]/g, '').trim()
  if (!cleaned || cleaned === '—' || cleaned === '-' || cleaned === 'N/A' || cleaned === 'null') {
    return { num: 0, hasValue: false, isNegative: false }
  }

  // Parenthesized negative number in financial reporting e.g. (1,234.5) -> -1234.5
  const parenthesizedMatch = cleaned.match(/^\(([\d,.]+)\)$/)
  if (parenthesizedMatch) {
    const val = parseFloat(parenthesizedMatch[1].replace(/,/g, ''))
    if (!isNaN(val)) return { num: -val, hasValue: true, isNegative: true }
  }

  const numMatch = cleaned.match(/^[-+]?[\d,]+(?:\.\d+)?/)
  if (numMatch) {
    const val = parseFloat(numMatch[0].replace(/,/g, ''))
    if (!isNaN(val)) return { num: val, hasValue: true, isNegative: val < 0 }
  }

  return { num: 0, hasValue: false, isNegative: false }
}

/**
 * Programmatic Footing and Cross-Footing Auditing (Section 4 of research paper).
 * Enforces vertical footing sum equality, horizontal reconciliation, and grand total convergence.
 */
export function auditTableFooting(table: CanonicalTable, tolerance: number = 0.05): TableAuditResult {
  const result: TableAuditResult = {
    isAudited: true,
    hasFooting: false,
    hasCrossFooting: false,
    grandTotalReconciled: true,
    verticalFootingErrors: [],
    horizontalFootingErrors: [],
    invariantErrors: []
  }

  const rows = table.rows
  const headers = table.headers
  if (rows.length < 2 || headers.length < 2) {
    result.auditBadge = 'unverifiable'
    return result
  }

  // Check if terminal row is a summary/total row
  const lastRowIdx = rows.length - 1
  const lastRowFirstCell = (rows[lastRowIdx][0] || '').replace(/[*_]/g, '').trim()
  const isSummaryRow = table.footingRowIndex !== undefined || /^(Total|Grand Total|Sum|Net|Consolidated Total)\b/i.test(lastRowFirstCell)

  if (isSummaryRow) {
    result.hasFooting = true
    const totalRowIdx = table.footingRowIndex !== undefined ? table.footingRowIndex : lastRowIdx
    const totalRow = rows[totalRowIdx]

    // Vertical Footing: For each numeric column j, check \sum_{i=1}^{n-1} Cell(i, j) == Cell(n, j)
    for (let j = 1; j < headers.length; j++) {
      const statedTotalParsed = extractNumericCell(totalRow[j])
      if (!statedTotalParsed.hasValue) continue

      let calculatedSum = 0
      let numericCount = 0

      for (let i = 0; i < totalRowIdx; i++) {
        const cellParsed = extractNumericCell(rows[i][j])
        if (cellParsed.hasValue) {
          calculatedSum += cellParsed.num
          numericCount++
        }
      }

      if (numericCount >= 2) {
        const diff = Math.abs(calculatedSum - statedTotalParsed.num)
        if (diff > tolerance) {
          result.verticalFootingErrors.push({
            colIndex: j,
            colHeader: headers[j] || `Col ${j + 1}`,
            expectedSum: Number(calculatedSum.toFixed(2)),
            statedTotal: statedTotalParsed.num,
            diff: Number(diff.toFixed(2))
          })
        }
      }
    }
  }

  // Horizontal Cross-Footing: If the last column is "Total" / "Sum" / "Net"
  const lastColIdx = headers.length - 1
  const lastColHeader = (headers[lastColIdx] || '').replace(/[*_]/g, '').trim()
  const isTotalCol = /^(Total|Grand Total|Sum|Net|All)\b/i.test(lastColHeader)

  if (isTotalCol) {
    result.hasCrossFooting = true
    for (let i = 0; i < rows.length; i++) {
      const statedTotalParsed = extractNumericCell(rows[i][lastColIdx])
      if (!statedTotalParsed.hasValue) continue

      let calculatedSum = 0
      let numericCount = 0

      for (let j = 1; j < lastColIdx; j++) {
        const cellParsed = extractNumericCell(rows[i][j])
        if (cellParsed.hasValue) {
          calculatedSum += cellParsed.num
          numericCount++
        }
      }

      if (numericCount >= 2) {
        const diff = Math.abs(calculatedSum - statedTotalParsed.num)
        if (diff > tolerance) {
          result.horizontalFootingErrors.push({
            rowIndex: i,
            rowLabel: rows[i][0] || `Row ${i + 1}`,
            expectedSum: Number(calculatedSum.toFixed(2)),
            statedTotal: statedTotalParsed.num,
            diff: Number(diff.toFixed(2))
          })
        }
      }
    }
  }

  // Assign audit badge
  if (result.verticalFootingErrors.length === 0 && result.horizontalFootingErrors.length === 0) {
    if (result.hasFooting || result.hasCrossFooting) {
      result.auditBadge = 'verified'
      result.summaryNote = 'Mathematical Footing & Cross-Footing Reconciled'
    } else {
      result.auditBadge = 'verified'
      result.summaryNote = 'Tabular Schema Consistent'
    }
  } else {
    result.auditBadge = 'discrepancy'
    result.summaryNote = `Found ${result.verticalFootingErrors.length + result.horizontalFootingErrors.length} mathematical discrepancies in footing.`
  }

  return result
}

