/**
 * Protects pipe characters within LaTeX math expressions (e.g. $|x|$, $P(A|B)$)
 * and backtick code expressions so table parsers don't split on them.
 */
export function protectNonTablePipes(text: string): { protectedText: string; restore: (str: string) => string } {
  const placeholders: string[] = []
  let count = 0

  // Protect LaTeX math ($...$, $$...$$, \(...\), \[...\])
  let protectedText = text.replace(/(\$\$[\s\S]*?\$\$|\$[^$\n]+?\$|\\\(.*?\\\)|\\\[[\s\S]*?\\\]|`[^`\n]+?`)/g, (match) => {
    if (match.includes('|')) {
      const placeholder = `___TABLE_PIPE_PROTECTED_${count++}___`
      placeholders.push(match)
      return placeholder
    }
    return match
  })

  const restore = (str: string): string => {
    let result = str
    for (let i = 0; i < placeholders.length; i++) {
      result = result.split(`___TABLE_PIPE_PROTECTED_${i}___`).join(placeholders[i])
    }
    return result
  }

  return { protectedText, restore }
}

/**
 * Deterministically repairs common LLM table formatting corruptions:
 * - Flattened single-line pipe tables
 * - Missing start/end boundary pipes
 * - Missing or broken separator rows
 * - Uneven column counts across rows
 */
export function repairMalformedTable(rawText: string): string {
  if (!rawText || typeof rawText !== 'string') return ''

  let text = rawText.trim()

  // 1. Single-line flattened table expansion
  if (!text.includes('\n') && text.includes('|')) {
    // Before separator row
    text = text.replace(/\|\s+(?=\|(?:\s*:?-{2,}:?\s*\|)+)/g, '|\n')
    // After separator row
    text = text.replace(/((?:\|(?:\s*:?-{2,}:?\s*)+)\|)\s+(?=\|)/g, '$1\n')
    // Between subsequent data rows
    text = text.replace(/([^\n|]+)\|\s+(?=\|)/g, '$1|\n')
  }

  const lines = text.split('\n').map(l => l.trim()).filter(Boolean)
  if (lines.length < 2) return text

  // 2. Identify header line & separator line
  let sepIndex = lines.findIndex(l => /^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)+\|?\s*$/.test(l))

  // If no separator row is present, synthesize one based on first row
  if (sepIndex === -1 && lines[0].includes('|')) {
    const firstRowCols = lines[0].split('|').map(c => c.trim()).filter(Boolean).length
    if (firstRowCols >= 2) {
      const syntheticSep = '| ' + Array(firstRowCols).fill('---').join(' | ') + ' |'
      lines.splice(1, 0, syntheticSep)
      sepIndex = 1
    }
  }

  if (sepIndex < 1) return text

  const splitCells = (line: string): string[] => {
    let l = line.trim()
    if (l.startsWith('|')) l = l.slice(1)
    if (l.endsWith('|')) l = l.slice(0, -1)
    return l.split('|').map(c => c.trim())
  }

  // 3. Ensure all lines have leading and trailing pipes and uniform column widths
  const headerLine = lines[sepIndex - 1]
  const headerCols = splitCells(headerLine)
  const sepCols = splitCells(lines[sepIndex])
  const maxCols = Math.max(headerCols.length, sepCols.length)

  const normalizedLines: string[] = []

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]
    let cells = splitCells(line)

    if (i === sepIndex) {
      while (cells.length < maxCols) cells.push('---')
      if (cells.length > maxCols) cells = cells.slice(0, maxCols)
      normalizedLines.push('| ' + cells.join(' | ') + ' |')
      continue
    }

    while (cells.length < maxCols) cells.push('')
    if (cells.length > maxCols) cells = cells.slice(0, maxCols)

    normalizedLines.push('| ' + cells.join(' | ') + ' |')
  }

  return normalizedLines.join('\n')
}

