/**
 * 2a. Parse Standard Markdown Pipe Table
 */
export function parseMarkdownPipeTable(text: string): CanonicalTable | null {
  if (!text || !text.includes('|')) return null

  const { protectedText, restore } = protectNonTablePipes(text)
  const repaired = repairMalformedTable(protectedText)
  const lines = repaired.split('\n').map(l => l.trim()).filter(Boolean)
  if (lines.length < 2) return null

  const sepIndex = lines.findIndex(l => /^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)+\|?\s*$/.test(l))
  if (sepIndex < 1) return null

  const splitCells = (line: string): string[] => {
    let l = line.trim()
    if (l.startsWith('|')) l = l.slice(1)
    if (l.endsWith('|')) l = l.slice(0, -1)
    return l.split('|').map(c => restore(c.trim()))
  }

  const rawHeaders = splitCells(lines[sepIndex - 1])
  const sepCells = splitCells(lines[sepIndex])
  if (rawHeaders.length === 0 || sepCells.length === 0) return null

  const colCount = Math.max(rawHeaders.length, sepCells.length)
  const alignments: TableAlignment[] = []

  for (let i = 0; i < colCount; i++) {
    const sep = sepCells[i] || ''
    const startsColon = sep.startsWith(':')
    const endsColon = sep.endsWith(':')
    if (startsColon && endsColon) {
      alignments.push('center')
    } else if (endsColon) {
      alignments.push('right')
    } else {
      alignments.push('left')
    }
  }

  const headers = rawHeaders.slice(0, colCount)
  while (headers.length < colCount) headers.push('')

  const rows: string[][] = []
  const hierarchicalDepth: number[] = []
  let footingRowIndex: number | undefined

  for (let i = sepIndex + 1; i < lines.length; i++) {
    const line = lines[i]
    if (!line.includes('|')) break
    const cells = splitCells(line)
    const rowCells = cells.slice(0, colCount)
    while (rowCells.length < colCount) rowCells.push('')

    // Detect hierarchical depth from leading spaces or indentation dashes in first cell
    const firstCell = rowCells[0] || ''
    const depthMatch = firstCell.match(/^(\s{2,}|[—–-]{1,3}\s*|\t+)/)
    let depth = 0
    if (depthMatch) {
      depth = Math.min(3, Math.floor(depthMatch[0].length / 2) || 1)
      rowCells[0] = firstCell.replace(/^(\s{2,}|[—–-]{1,3}\s*|\t+)/, '').trim()
    }
    hierarchicalDepth.push(depth)

    // Detect footing / total row
    const isTotalRow = /^(Total|Grand Total|Sum|Net Total|Consolidated Total|All Categories)\b/i.test(rowCells[0].replace(/[*_]/g, '').trim())
    if (isTotalRow) {
      footingRowIndex = rows.length
    }

    rows.push(rowCells)
  }

  if (rows.length === 0) return null

  const table: CanonicalTable = {
    headers,
    alignments,
    rows,
    hierarchicalDepth,
    footingRowIndex,
    format: 'markdown'
  }

  table.auditResult = auditTableFooting(table)
  return table
}

/**
 * 2b. Parse HTML Table (<table>...</table>)
 */
export function parseHTMLTable(html: string): CanonicalTable | null {
  if (!html || !/<table[\s>]/i.test(html)) return null

  try {
    const parser = new DOMParser()
    const doc = parser.parseFromString(html, 'text/html')
    const tableEl = doc.querySelector('table')
    if (!tableEl) return null

    const headerEls = Array.from(tableEl.querySelectorAll('thead tr th, tr th'))
    let headers: string[] = []

    if (headerEls.length > 0) {
      // Find row of headers
      const theadRow = tableEl.querySelector('thead tr') || tableEl.querySelector('tr')
      if (theadRow) {
        headers = Array.from(theadRow.querySelectorAll('th, td')).map(c => c.textContent?.trim() || '')
      }
    }

    const rowEls = Array.from(tableEl.querySelectorAll('tbody tr, table > tr'))
    const dataRowEls = headerEls.length > 0 && !tableEl.querySelector('tbody') ? rowEls.slice(1) : rowEls
    const rows: string[][] = []
    const hierarchicalDepth: number[] = []
    let footingRowIndex: number | undefined

    for (const tr of dataRowEls) {
      const cells = Array.from(tr.querySelectorAll('td, th')).map(c => c.textContent?.trim() || '')
      if (cells.length === 0) continue

      if (headers.length === 0) {
        headers = cells
        continue
      }

      // Check depth / class
      const depthAttr = tr.getAttribute('data-depth') || tr.getAttribute('level')
      const depth = depthAttr ? parseInt(depthAttr, 10) || 0 : 0
      hierarchicalDepth.push(depth)

      if (/^(Total|Grand Total|Sum|Net Total)\b/i.test(cells[0] || '')) {
        footingRowIndex = rows.length
      }

      rows.push(cells)
    }

    if (headers.length === 0 && rows.length > 0) {
      headers = rows.shift() || []
    }

    if (headers.length === 0) return null

    // Normalize column counts
    const colCount = headers.length
    for (let r = 0; r < rows.length; r++) {
      while (rows[r].length < colCount) rows[r].push('')
      if (rows[r].length > colCount) rows[r] = rows[r].slice(0, colCount)
    }

    const alignments: TableAlignment[] = Array(colCount).fill('left')

    const table: CanonicalTable = {
      headers,
      alignments,
      rows,
      hierarchicalDepth,
      footingRowIndex,
      format: 'html'
    }

    table.auditResult = auditTableFooting(table)
    return table
  } catch {
    return null
  }
}

/**
 * 2c. Parse Markdown-KV (Markdown Key-Value / Record format)
 * Benchmark proven highest LLM comprehension accuracy format (60.7%).
 * Example syntax:
 * Row: {"Year": "2023", "Revenue": "$100M", "Net Income": "$20M"}
 * or:
 * Record 1: Metric = GDP | Q1 = 28245.9 | Q2 = 28650.2
 */
export function parseMarkdownKVTable(text: string): CanonicalTable | null {
  if (!text) return null
  const lines = text.split('\n').map(l => l.trim()).filter(Boolean)
  if (lines.length === 0) return null

  const kvRecords: Record<string, string>[] = []

  for (const line of lines) {
    // Format A: Row: {"Key": "Val", ...} or Row 1: {Asset: Cash, Amount: $500}
    const jsonMatch = line.match(/^(?:(?:Row|Record|Item)\s*\d*|\d+)\s*[:：]?\s*(\{.*\})$/i)
    if (jsonMatch) {
      let parsed = false
      try {
        const obj = JSON.parse(jsonMatch[1])
        if (typeof obj === 'object' && obj !== null) {
          const stringified: Record<string, string> = {}
          for (const [k, v] of Object.entries(obj)) {
            stringified[k] = v !== undefined && v !== null ? String(v) : ''
          }
          kvRecords.push(stringified)
          parsed = true
          continue
        }
      } catch {}

      if (!parsed) {
        // Relaxed pseudo-JSON / YAML-like {k: v, k2: v2}
        const inner = jsonMatch[1].replace(/^\{|\}$/g, '').trim()
        const pairs = inner.split(/,\s*(?=[^,]+:)/).map(p => p.trim()).filter(Boolean)
        const record: Record<string, string> = {}
        let foundPair = false
        for (const pair of pairs) {
          const colonIdx = pair.indexOf(':')
          if (colonIdx > 0) {
            const k = pair.slice(0, colonIdx).replace(/^["']|["']$/g, '').trim()
            const v = pair.slice(colonIdx + 1).replace(/^["']|["']$/g, '').trim()
            if (k && v) {
              record[k] = v
              foundPair = true
            }
          }
        }
        if (foundPair) {
          kvRecords.push(record)
          continue
        }
      }
    }

    // Format B: Key = Value | Key2 = Value2
    if (line.includes('=') && (line.includes('|') || line.includes(';'))) {
      const parts = line.split(/[|;]/).map(p => p.trim()).filter(Boolean)
      const record: Record<string, string> = {}
      let foundPair = false
      for (const part of parts) {
        const eqIdx = part.indexOf('=')
        if (eqIdx > 0) {
          const k = part.slice(0, eqIdx).replace(/^(?:(?:Row|Record|Item)\s*\d*|\d+)\s*[:：]?\s*/i, '').trim()
          const v = part.slice(eqIdx + 1).trim()
          if (k && v) {
            record[k] = v
            foundPair = true
          }
        }
      }
      if (foundPair) {
        kvRecords.push(record)
      }
    }
  }

  if (kvRecords.length < 2) return null

  // Extract unique headers in order of appearance
  const headerSet = new Set<string>()
  for (const rec of kvRecords) {
    for (const key of Object.keys(rec)) {
      headerSet.add(key)
    }
  }

  const headers = Array.from(headerSet)
  if (headers.length < 2) return null

  const alignments: TableAlignment[] = Array(headers.length).fill('left')
  const rows: string[][] = []

  for (const rec of kvRecords) {
    const row = headers.map(h => rec[h] !== undefined ? String(rec[h]) : '')
    rows.push(row)
  }

  const table: CanonicalTable = {
    headers,
    alignments,
    rows,
    format: 'markdown_kv'
  }

  table.auditResult = auditTableFooting(table)
  return table
}

/**
 * 2d. Parse LaTeX Tabular & Booktabs Environment
 * Supports \begin{tabular}{...}, \toprule, \midrule, \bottomrule, \multicolumn,
 * econometric point estimates with standard errors in parentheses, and significance stars.
 */
export function parseLatexTabular(text: string): CanonicalTable | null {
  if (!text || !/\\begin\{(?:tabular|table|booktabs)\*?\}/i.test(text)) return null

  try {
    const bodyMatch = text.match(/\\begin\{(?:tabular|table|booktabs)\*?\}(?:\{([^}]*)\})?([\s\S]*?)\\end\{(?:tabular|table|booktabs)\*?\}/i)
    if (!bodyMatch) return null

    const alignSpec = bodyMatch[1] || ''
    const content = bodyMatch[2]

    // Parse column alignments from LaTeX spec (e.g. {l c r r})
    const alignments: TableAlignment[] = []
    if (alignSpec) {
      for (const char of alignSpec) {
        if (char === 'l') alignments.push('left')
        else if (char === 'c') alignments.push('center')
        else if (char === 'r') alignments.push('right')
      }
    }

    // Clean rule commands and split content by LaTeX row terminator \\
    const rawSegments = content
      .split(/\\\\(?:\s*\[[^\]]*\])?/)
      .map(r => r.replace(/\\(?:hline|toprule|midrule|bottomrule|cline\{[^}]*\})/g, '').trim())
      .filter(r => r.length > 0)

    if (rawSegments.length < 2) return null

    const parsedRows: string[][] = []
    for (const r of rawSegments) {
      // Split by & column separator
      const cells = r.split('&').map(c => {
        let cell = c.trim()
        // Strip \multicolumn{1}{c}{value} -> value
        const multiMatch = cell.match(/\\multicolumn\{\d+\}\{[^}]*\}\{(.*?)\}/)
        if (multiMatch) cell = multiMatch[1].trim()
        // Clean text formatting \textbf{...} -> **...**, \textit{...} -> *...*
        cell = cell.replace(/\\textbf\{(.*?)\}/g, '**$1**').replace(/\\textit\{(.*?)\}/g, '*$1*')
        return cell
      })
      parsedRows.push(cells)
    }

    if (parsedRows.length < 2) return null

    const headers = parsedRows[0]
    const rows = parsedRows.slice(1)
    const colCount = headers.length

    while (alignments.length < colCount) alignments.push('left')

    // Normalize rows
    for (let r = 0; r < rows.length; r++) {
      while (rows[r].length < colCount) rows[r].push('')
      if (rows[r].length > colCount) rows[r] = rows[r].slice(0, colCount)
    }

    const table: CanonicalTable = {
      headers,
      alignments: alignments.slice(0, colCount),
      rows,
      format: 'latex_tabular'
    }

    table.auditResult = auditTableFooting(table)
    return table
  } catch {
    return null
  }
}

/**
 * 2e. Parse CSV / TSV format tables
 */
export function parseCSVTable(text: string): CanonicalTable | null {
  if (!text || (!text.includes(',') && !text.includes('\t'))) return null
  const lines = text.split('\n').map(l => l.trim()).filter(Boolean)
  if (lines.length < 2) return null

  // Ensure lines are not markdown list items, blockquotes, or headings
  for (const line of lines) {
    if (/^\s*([-*+•]|\d+[.)]|\([a-zA-Z0-9]+\))\s+/.test(line)) return null
    if (/^\s*[>#]/.test(line)) return null
  }

  const isTSV = lines[0].includes('\t')
  const delimiter = isTSV ? '\t' : ','

  const rows: string[][] = []
  for (const line of lines) {
    if (line.startsWith('#')) continue
    // Handle CSV quoting
    const cells: string[] = []
    let current = ''
    let inQuotes = false

    for (let i = 0; i < line.length; i++) {
      const char = line[i]
      if (char === '"') {
        inQuotes = !inQuotes
      } else if (char === delimiter && !inQuotes) {
        cells.push(current.trim())
        current = ''
      } else {
        current += char
      }
    }
    cells.push(current.trim())
    if (cells.length > 0) rows.push(cells)
  }

  if (rows.length < 2) return null

  const headers = rows[0]
  const dataRows = rows.slice(1)
  const colCount = headers.length
  if (colCount < 2) return null

  // Headers must be reasonable (e.g. not long paragraphs or ending in question marks)
  if (headers.some(h => h.length > 80 || /[?!]$/.test(h))) return null

  // All data rows should have at least 2 columns and reasonably match header column count
  if (dataRows.some(r => r.length === 1)) return null

  for (let r = 0; r < dataRows.length; r++) {
    while (dataRows[r].length < colCount) dataRows[r].push('')
    if (dataRows[r].length > colCount) dataRows[r] = dataRows[r].slice(0, colCount)
  }

  const alignments: TableAlignment[] = Array(colCount).fill('left')

  const table: CanonicalTable = {
    headers,
    alignments,
    rows: dataRows,
    format: isTSV ? 'tsv' : 'csv'
  }

  table.auditResult = auditTableFooting(table)
  return table
}

/**
 * 2f. Universal Table Dispatcher: Auto-detects and parses any table representation
 */
export function parseUniversalTable(text: string): CanonicalTable | null {
  if (!text || typeof text !== 'string') return null
  const trimmed = text.trim()

  // 1. LaTeX Tabular
  if (/\\begin\{(?:tabular|table|booktabs)\*?\}/i.test(trimmed)) {
    const res = parseLatexTabular(trimmed)
    if (res) return res
  }

  // 2. HTML Table
  if (/<table[\s>]/i.test(trimmed)) {
    const res = parseHTMLTable(trimmed)
    if (res) return res
  }

  // 3. Markdown Pipe Table (most common in LLM chat/markdown)
  if (trimmed.includes('|')) {
    const res = parseMarkdownPipeTable(trimmed)
    if (res) return res
  }

  // 4. Markdown-KV
  if (/^(?:(?:Row|Record|Item)\s*\d*|\d+)\s*[:：]?\s*\{/im.test(trimmed) || (trimmed.includes('=') && (trimmed.includes('|') || trimmed.includes(';')))) {
    const res = parseMarkdownKVTable(trimmed)
    if (res) return res
  }

  // 5. CSV / TSV
  if (trimmed.includes(',') || trimmed.includes('\t')) {
    const res = parseCSVTable(trimmed)
    if (res) return res
  }

  return null
}

