// 5. MULTI-FORMAT SERIALIZATION & EXPORTERS
// ═══════════════════════════════════════════════════════════════════════════════

export function exportTableAs(
  table: CanonicalTable,
  format: 'markdown' | 'csv' | 'tsv' | 'latex' | 'html' | 'json'
): string {
  const { headers, alignments, rows } = table

  switch (format) {
    case 'markdown': {
      const sepRow = alignments.map(a => {
        if (a === 'center') return ':---:'
        if (a === 'right') return '---:'
        return '---'
      })
      const lines = [
        '| ' + headers.join(' | ') + ' |',
        '| ' + sepRow.join(' | ') + ' |',
        ...rows.map(r => '| ' + r.join(' | ') + ' |')
      ]
      return lines.join('\n')
    }

    case 'csv': {
      const escapeCSV = (str: string) => `"${str.replace(/"/g, '""')}"`
      const lines = [
        headers.map(escapeCSV).join(','),
        ...rows.map(r => r.map(escapeCSV).join(','))
      ]
      return lines.join('\n')
    }

    case 'tsv': {
      const lines = [
        headers.join('\t'),
        ...rows.map(r => r.join('\t'))
      ]
      return lines.join('\n')
    }

    case 'latex': {
      const alignChars = alignments.map(a => a[0]).join(' ')
      const lines = [
        `\\begin{tabular}{${alignChars}}`,
        '\\toprule',
        headers.join(' & ') + ' \\\\',
        '\\midrule',
        ...rows.map(r => r.join(' & ') + ' \\\\'),
        '\\bottomrule',
        '\\end{tabular}'
      ]
      return lines.join('\n')
    }

    case 'html': {
      const lines = [
        '<table class="table-auto border-collapse w-full">',
        '  <thead>',
        '    <tr>',
        ...headers.map(h => `      <th class="border p-2 font-semibold">${h}</th>`),
        '    </tr>',
        '  </thead>',
        '  <tbody>',
        ...rows.map(r => [
          '    <tr>',
          ...r.map(c => `      <td class="border p-2">${c}</td>`),
          '    </tr>'
        ].join('\n')),
        '  </tbody>',
        '</table>'
      ]
      return lines.join('\n')
    }

    case 'json': {
      const records = rows.map(r => {
        const obj: Record<string, string> = {}
        headers.forEach((h, i) => {
          obj[h] = r[i] || ''
        })
        return obj
      })
      return JSON.stringify(records, null, 2)
    }
  }
}
