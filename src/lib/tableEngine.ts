// ═══════════════════════════════════════════════════════════════════════════════

/**
 * Transforms any structured table into high-yield atomic flashcards and active recall items
 * across Bloom's Taxonomy and Matuschak's 5 conceptual lenses.
 */
export function generateCardsFromTable(
  table: CanonicalTable,
  topicName: string = 'Tabular Knowledge'
): AutoGeneratedFlashcard[] {
  const cards: AutoGeneratedFlashcard[] = []
  const { headers, rows } = table
  if (headers.length < 2 || rows.length === 0) return cards

  // Strategy 1: Row-by-Row Atomic Extraction
  for (let r = 0; r < rows.length; r++) {
    const row = rows[r]
    const primaryEntity = row[0]
    if (!primaryEntity || primaryEntity.trim() === '') continue
    if (/^(Total|Grand Total|Sum|Average|Mean|Summary)\b/i.test(primaryEntity)) continue

    for (let c = 1; c < headers.length; c++) {
      const colHeader = headers[c]
      const cellValue = row[c]
      if (!cellValue || cellValue.trim() === '' || cellValue === '—' || cellValue === '-') continue

      // Clean Markdown / LaTeX formatting for front
      const cleanEntity = primaryEntity.replace(/[*_#]/g, '').trim()
      const cleanHeader = colHeader.replace(/[*_#]/g, '').trim()
      const cleanValue = cellValue.trim()

      // Detect econometric regression table row (Coefficient and Standard Error)
      const isEconoTable = cleanValue.includes('(') && cleanValue.includes(')') && /[*0-9]/.test(cleanValue)

      if (isEconoTable) {
        cards.push({
          front: `[${topicName}: Econometrics] In the regression model for "${cleanHeader}", what is the estimated coefficient and significance for "${cleanEntity}"?`,
          back: cleanValue,
          concept: topicName,
          card_type: 'Basic_QA',
          conceptual_lens: 'Attributes',
          bloom_level: 'Understanding',
          pedagogical_rationale: `Tests econometric parameter point estimate and clustered error for ${cleanEntity}`
        })
      } else {
        cards.push({
          front: `[${topicName}] What is the "${cleanHeader}" for "${cleanEntity}"?`,
          back: cleanValue,
          concept: topicName,
          card_type: 'Basic_QA',
          conceptual_lens: 'Attributes',
          bloom_level: 'Remembering',
          pedagogical_rationale: `Tests the specific attribute ${cleanHeader} of ${cleanEntity}`
        })
      }
    }
  }

  // Strategy 2: Differential Discrimination across Columns (Bloom Level 4)
  if (headers.length >= 3 && rows.length >= 2) {
    const colA = headers[1].replace(/[*_#]/g, '').trim()
    const colB = headers[2].replace(/[*_#]/g, '').trim()
    const targetRow = rows[0]
    const entity = targetRow[0].replace(/[*_#]/g, '').trim()
    const valA = targetRow[1]
    const valB = targetRow[2]

    if (valA && valB && valA !== valB && valA !== '—' && valB !== '—') {
      cards.push({
        front: `[${topicName}: Comparison] For "${entity}", how does "${colA}" ($${valA}$) compare against "${colB}" ($${valB}$)?`,
        back: `${colA}: ${valA} vs ${colB}: ${valB}`,
        concept: topicName,
        card_type: 'Differential',
        conceptual_lens: 'Differences',
        bloom_level: 'Analyzing',
        pedagogical_rationale: `Discriminates comparative metrics between ${colA} and ${colB}`
      })
    }
  }

  return cards
}

